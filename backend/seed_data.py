async def seed_database():
    """Seed the database with ES objects"""
    mongo_url = os.environ['MONGO_URL']
    client = AsyncIOMotorClient(mongo_url)
    db = client[os.environ['DB_NAME']]
    
    # Clear existing objects
    await db.es_objects.delete_many({})
    
    # Insert new objects
    await db.es_objects.insert_many(ES_OBJECTS)
    
    print(f"✅ Successfully seeded {len(ES_OBJECTS)} ES objects")
    
    client.close()

if __name__ == "__main__":
    asyncio.run(seed_database())
